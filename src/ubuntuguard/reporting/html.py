def render_html_report(payload: dict[str, Any]) -> str:
    host = payload.get("host", {}) if isinstance(payload.get("host"), dict) else {}
    audit = payload.get("audit", {}) if isinstance(payload.get("audit"), dict) else {}
    detection = (
        payload.get("detection", {})
        if isinstance(payload.get("detection"), dict)
        else {}
    )
    monitoring = (
        payload.get("monitoring", {})
        if isinstance(payload.get("monitoring"), dict)
        else {}
    )

    audit_summary = audit.get("summary", {}) or {}
    checks = monitoring.get("checks", []) or []
    critical_checks = sum(
        1 for check in checks if check.get("status") == "critical"
    )

    parts = [
        "<!DOCTYPE html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width, initial-scale=1">',
        "<title>UbuntuGuard report</title>",
        f"<style>{_CSS}</style></head><body>",
        "<header><h1>UbuntuGuard report</h1>",
        f"<p>{_e(host.get('hostname', 'unknown'))} · "
        f"{_e(host.get('os', 'unknown'))} · kernel "
        f"{_e(host.get('kernel', 'unknown'))} · "
        f"{_e(payload.get('generated_at', ''))}</p></header>",
        "<main>",
        '<section><h2>Overview</h2><div class="cards">',
        _card(
            "Audit score",
            f"{audit_summary.get('score', '-')}/100 ({audit_summary.get('grade', '-')})",
        ),
        _card("Audit findings", str(audit_summary.get("total", 0))),
        _card(
            "Detection findings",
            str(len(detection.get("findings", []) or [])),
        ),
        _card("Health checks", f"{len(checks)} checks, {critical_checks} critical"),
        "</div></section>",
    ]

    parts.append(
        _findings_section("Audit findings", audit.get("findings", []) or [])
    )
    parts.append(
        _findings_section(
            "Detection findings", detection.get("findings", []) or []
        )
    )
    parts.append(_checks_section(checks))
    parts.append(_skipped_section("Skipped checks", _collect_skipped(audit, detection)))
    parts.append(
        _errors_section(
            monitoring.get("metrics", {}).get("errors", [])
            if isinstance(monitoring.get("metrics"), dict)
            else []
        )
    )

    parts.append(
        '<section><h2>Metadata</h2><p class="muted">'
        f"schema {_e(payload.get('schema_version', '1.0'))} · "
        f"generated by UbuntuGuard {_e(payload.get('tool_version', ''))}"
        "</p></section>"
    )
    parts.append("</main></body></html>")
    return "\n".join(parts)


def _findings_section(title: str, findings: list[Any]) -> str:
    rows: list[str] = []
    for item in findings:
        if not isinstance(item, dict):
            continue
        rows.append(
            "<tr>"
            f"<td><code>{_e(item.get('id', ''))}</code></td>"
            f"<td>{_badge(str(item.get('severity', 'info')))}</td>"
            f"<td>{_e(item.get('title', ''))}"
            f"<div class=\"muted\">{_e(item.get('remediation', ''))}</div></td>"
            f"<td><code>{_e(_compact(item.get('evidence', {})))}</code></td>"
            "</tr>"
        )
    if not rows:
        rows.append('<tr><td colspan="4" class="muted">No findings</td></tr>')
    return (
        f"<section><h2>{_e(title)}</h2><table>"
        "<thead><tr><th>ID</th><th>Severity</th><th>Finding</th>"
        "<th>Evidence</th></tr></thead><tbody>"
        + "".join(rows)
        + "</tbody></table></section>"
    )


def _checks_section(checks: list[Any]) -> str:
    rows: list[str] = []
    for check in checks:
        if not isinstance(check, dict):
            continue
        rows.append(
            "<tr>"
            f"<td>{_e(check.get('name', ''))}</td>"
            f"<td>{_badge(str(check.get('status', 'ok')))}</td>"
            f"<td>{_e(check.get('value'))}</td>"
            f"<td>{_e(check.get('threshold'))}</td>"
            f"<td>{_e(check.get('detail', ''))}</td>"
            "</tr>"
        )
    if not rows:
        rows.append('<tr><td colspan="5" class="muted">No checks</td></tr>')
    return (
        "<section><h2>Health checks</h2><table>"
        "<thead><tr><th>Check</th><th>Status</th><th>Value</th>"
        "<th>Threshold</th><th>Detail</th></tr></thead><tbody>"
        + "".join(rows)
        + "</tbody></table></section>"
    )


def _skipped_section(title: str, skipped: list[str]) -> str:
    if not skipped:
        return f"<section><h2>{_e(title)}</h2><p class=\"muted\">None</p></section>"
    items = "".join(f"<li>{_e(reason)}</li>" for reason in skipped)
    return f"<section><h2>{_e(title)}</h2><ul>{items}</ul></section>"


def _errors_section(errors: list[Any]) -> str:
    if not errors:
        return ""
    items = "".join(f"<li>{_e(error)}</li>" for error in errors)
    return f"<section><h2>Collection errors</h2><ul>{items}</ul></section>"


def _collect_skipped(audit: dict[str, Any], detection: dict[str, Any]) -> list[str]:
    skipped: list[str] = []
    for source in (audit.get("skipped", []), detection.get("skipped", [])):
        if isinstance(source, list):
            skipped.extend(str(item) for item in source)
    return skipped


def _card(label: str, value: str) -> str:
    return (
        f'<div class="card"><span>{_e(label)}</span>'
        f"<strong>{_e(value)}</strong></div>"
    )


def _badge(value: str) -> str:
    css = value.lower() if value.lower() in {
        "critical",
        "high",
        "medium",
        "low",
        "info",
        "ok",
        "skipped",
    } else "info"
    return f'<span class="badge {css}">{_e(value)}</span>'


def _compact(value: Any) -> str:
    if isinstance(value, dict):
        return ", ".join(f"{key}={value[key]}" for key in list(value)[:4])
    return str(value)


def _e(value: Any) -> str:
    return html.escape("" if value is None else str(value), quote=True)
